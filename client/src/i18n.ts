const ITEMS_TRANSLATIONS: Record<string, string> = ITEMS_EN;
const RARITY_EN: Record<string, string> = { Incomum: 'Uncommon', Rara: 'Rare', Épica: 'Epic', Lendária: 'Legendary', Mítica: 'Mythic', Divina: 'Divine', Ancestral: 'Ancestral' };

export function itemName(ptName: string): string {
  if (currentLang === 'pt') return ptName;
  if (ITEMS_TRANSLATIONS[ptName]) return ITEMS_TRANSLATIONS[ptName];
  // Gema de Combate: "Gema: Bola de Fogo (Arcanista)" → "Gem: Fireball (Arcanist)".
  const gem = /^(Gema|Gema Lapidada|Gema Perfeita): (.+) \((Guerreiro|Caçador|Arcanista|Devoto)\)$/.exec(ptName);
  if (gem) {
    const s = SPELLS.find((x) => x.name === gem[2]);
    const voc = { Guerreiro: 'Warrior', Caçador: 'Hunter', Arcanista: 'Arcanist', Devoto: 'Devout' }[gem[3]];
    const kind = { Gema: 'Gem', 'Gema Lapidada': 'Cut Gem', 'Gema Perfeita': 'Perfect Gem' }[gem[1]];
    if (s) return `${kind}: ${t(`spell.${s.id}.name`, s.name)} (${voc})`;
  }
  // Peça com raridade e/ou refino: "Arco Curto (Épica) +3" → "Shortbow (Epic) +3".
  const m = /^(.+?)(?: \((Incomum|Rara|Épica|Lendária|Mítica|Divina|Ancestral)\))?( \+\d+)?$/.exec(ptName);
  if (m && (m[2] || m[3])) return `${ITEMS_TRANSLATIONS[m[1]] ?? m[1]}${m[2] ? ` (${RARITY_EN[m[2]]})` : ''}${m[3] ?? ''}`;
  return ptName;
}

