type Listener = (lang: Lang) => void;
const listeners = new Set<Listener>();

function detectInitialLang(): Lang {
  try {
    const saved = localStorage.getItem('grimhold.lang');
    if (saved === 'pt' || saved === 'en') return saved;
    const nav = navigator.language?.toLowerCase() ?? '';
    if (nav.startsWith('pt')) return 'pt';
    return 'en';
  } catch {
    return 'pt';
  }
}

let currentLang: Lang = detectInitialLang();

export function getLang(): Lang {
  return currentLang;
}

export function setLang(lang: Lang) {
  if (currentLang === lang) return;
  currentLang = lang;
  try {
    localStorage.setItem('grimhold.lang', lang);
  } catch {}
  localizeContent();
  for (const l of listeners) l(lang);
}

const CONTENT_TRANSLATIONS: Record<string, string> = CONTENT_EN;
// Texto original (português) de cada campo trocado, para voltar ao trocar de idioma.
const originals = new WeakMap<object, Record<string, string>>();

/**
 * Nomes de caçadas, monstros, chefes, arena, imbuements, mascotes e bonecos vêm
 * dos dados compartilhados em português. No inglês, troca o texto nos próprios
 * objetos (assim o mapa, as listas e as janelas mostram o nome traduzido) e
 * guarda o original para voltar ao português.
 */
function localizeContent() {
  const fix = (obj: unknown, fields: string[]) => {
    if (!obj || typeof obj !== 'object') return;
    const o = obj as Record<string, unknown>;
    let orig = originals.get(o);
    if (!orig) {
      orig = {};
      for (const f of fields) if (typeof o[f] === 'string') orig[f] = o[f] as string;
      originals.set(o, orig);
    }
    for (const [f, pt] of Object.entries(orig)) o[f] = currentLang === 'pt' ? pt : (CONTENT_TRANSLATIONS[pt] ?? pt);
  };
  const lists: [unknown, string[]][] = [
    [HUNTS, ['name', 'region']],
    [MONSTERS, ['name']],
    [WORLD_BOSSES, ['name', 'shout']],
    [IMBUEMENTS, ['name', 'description']],
    [PETS, ['name', 'description']],
    [DUMMY_NODES, ['name', 'description']],
    [OUTFIT_DEFS, ['name', 'description']],
  ];
  for (const [list, fields] of lists) for (const x of (list as unknown[]) ?? []) fix(x, fields);
  for (const a of (ARENAS as unknown as { opponents?: unknown[] }[]) ?? []) {
    fix(a, ['name']);
    for (const op of a.opponents ?? []) fix(op, ['name']);
  }
}

export function onLangChange(listener: Listener): () => void {
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
  };
}

