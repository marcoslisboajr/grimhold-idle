/**
 * XP das tarefas de caça: pelo menos HUNTING_TASK_XP_LEVEL de um nível de combate do nível da tarefa
 * (do 60 para cima pagava de 7% a quase 0% de um nível). Quem já pagava mais fica como está.
 */
export const HUNTING_TASK_XP_LEVEL = 0.08;
for (const t of HUNTING_TASKS) {
  const floor = Math.round(HUNTING_TASK_XP_LEVEL * (xpForLevel(t.minLevel + 1) - xpForLevel(t.minLevel)));
  if (t.xpReward < floor) t.xpReward = floor;
}

export const huntingTaskById = (id: string): HuntingTaskDef | undefined => HUNTING_TASKS.find((t) => t.id === id);

/** 26/10: do 400 em diante as tarefas liberam pelo nível das caçadas (combate + Maestria), como as caçadas. */
export const taskHuntLevel = (combatLevel: number, masteryLevel = 0) => huntLevelFor(combatLevel, masteryLevel);
/**
 * 26/10: tarefa muito abaixo do seu nível paga menos pontos (no 463, a do 205 dava mais pontos por abate que a do 463).
 * Até 25 níveis abaixo: cheio; depois -1% por nível, até 25%.
 */
export const TASK_POINTS_FREE_GAP = 25;
export function taskPointsFor(def: HuntingTaskDef, huntLevel: number): number {
  const gap = huntLevel - def.minLevel - TASK_POINTS_FREE_GAP;
  const f = gap <= 0 ? 1 : Math.max(0.25, 1 - gap / 100);
  return Math.max(1, Math.round(def.points * f));
}

/**
 * Destaques do dia (24/10): o Mestre Alden sugere 3 tarefas da faixa do jogador (entre as 8 mais altas que
 * ele alcança), que pagam +50% de pontos e de ouro se entregues no mesmo dia. Sorteio estável por dia.
 */
export const FEATURED_TASK_COUNT = 3;
export const FEATURED_TASK_BONUS = 0.5;
export function featuredTasksFor(characterId: number, day: string, level: number): string[] {
  // Começa junto com as diárias novas (25/10).
  if (day < '2026-10-25') return [];
  const pool = HUNTING_TASKS.filter((t) => t.minLevel <= Math.max(1, level)).sort((a, b) => b.minLevel - a.minLevel).slice(0, 8);
  let h = [...day].reduce((x, c) => Math.imul(x ^ c.charCodeAt(0), 16777619) >>> 0, 2166136261 ^ characterId);
  const rand = () => ((h = Math.imul(h ^ (h >>> 15), 2246822507) >>> 0), (h ^= h >>> 13), (h >>> 0) / 4294967296);
  const out: string[] = [];
  while (out.length < FEATURED_TASK_COUNT && pool.length) out.push(pool.splice(Math.floor(rand() * pool.length), 1)[0].id);
  return out;
}

export interface HunterRank {
  name: string;
  minPoints: number;
  trophyItem?: string;
  badge: string;
}

export const HUNTER_RANKS: HunterRank[] = [
  { name: 'Iniciante', minPoints: 0, badge: 'Iniciante' },
  { name: 'Rastreador', minPoints: 50, trophyItem: 'hunter_trophy_bronze', badge: 'Rastreador' },
  { name: 'Caçador de Elite', minPoints: 150, trophyItem: 'hunter_trophy_silver', badge: 'Elite' },
  { name: 'Predador Lendário', minPoints: 300, trophyItem: 'hunter_trophy_gold', badge: 'Lendário' },
];

export function rankForPoints(points: number): HunterRank {
  let best = HUNTER_RANKS[0];
  for (const r of HUNTER_RANKS) {
    if (points >= r.minPoints) best = r;
  }
  return best;
}
